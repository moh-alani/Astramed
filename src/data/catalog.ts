function makeBaseline(overrides: Partial<Record<Indicator, number>>) {
  return Object.fromEntries(
    Object.entries({ ...base, ...overrides }).map(([id, value]) => [
      id,
      {
        value,
        count: id === "reaction" ? 5 : 14,
        source: "Synthetic preflight",
      },
    ]),
  ) as Astronaut["baseline"];
}
